import React from 'react';
import { KeyboardAvoidingView, Pressable, StyleProp, StyleSheet, ViewStyle } from 'react-native';

/**
 * يرفع محتوى النافذة فوق لوحة المفاتيح بدل أن تُدفن تحتها.
 *
 * لوحة الآيباد تأخذ نحو نصف الشاشة، والنوافذ هنا موسّطة رأسياً. فحين
 * يلمس الكاشير حقل المبلغ، تفتح اللوحة فوق النافذة نفسها -- فيختفي
 * الحقل وزر التأكيد معاً، ولا سبيل إلى إغلاقها إلا بتخمين مكان زر
 * الإلغاء. وهو ما بلّغ عنه الكاشير حرفياً: تختفي النافذة والزر.
 *
 * والعلاج طبقة واحدة مشتركة لا إصلاحٌ في كل نافذة: النوافذ ذات الحقول
 * كثيرة، ولو عولجت واحدةً واحدةً لعادت المشكلة مع أول نافذة جديدة
 * ينساها كاتبها.
 *
 * behavior على iOS يكون 'padding': النافذة موسّطة داخل حاوية تملأ
 * الشاشة، فزيادة حشوٍ سفلي بارتفاع اللوحة تدفع المحتوى لأعلى وتُبقيه
 * موسّطاً في ما بقي. وعلى أندرويد كذلك: كان 'height' بحجّة أن
 * adjustResize يرفع النافذة بنفسه، لكن التطبيق مرسومٌ حافةً لحافة
 * (edgeToEdgeEnabled) والنوافذ <Modal>، وفي الحالتين لا يرفع
 * adjustResize شيئاً -- فبقي حقل بدء الوردية وزرّه تحت اللوحة على
 * سنمي D2 mini. فالحشو هنا هو الرافع الوحيد، لا رافعٌ ثانٍ.
 *
 * وهو <View> في كل شيء آخر: يأخذ نفس النمط، ويُوضع مكان طبقة النافذة
 * تماماً، فلا يتغيّر شكل شيء حين تكون اللوحة مغلقة.
 */
export default function KeyboardLift({
  style,
  children,
  onBackdropPress,
}: {
  style?: StyleProp<ViewStyle>;
  children: React.ReactNode;
  /**
   * الضغط على العتمة حول النافذة يقفلها -- ما يتوقّعه كل من استعمل
   * جوالاً. وكان لا سبيل إلى الإغلاق إلا إصابة زر ✕ في زاويةٍ صغيرة،
   * واليد ممتلئةٌ وقت الزحمة.
   *
   * والطبقةُ الملموسة تُرسم **قبل** المحتوى لا حوله: فالضغطة على
   * النافذة نفسها تصلها هي، ولا تمرّ بحارسٍ يبتلعها. ولو لُفّ المحتوى
   * بزرٍّ لاحتاج كلُّ ضغطٍ داخلَه إلى إيقاف تسلسل، وهو ما يكسر الحقول
   * والقوائم بصمت.
   *
   * ولا تُمرَّر لنافذةٍ لا يجوز تجاوزها بضغطةٍ طائشة -- طلبٌ جديد
   * ينتظر قبولاً أو رفضاً مثلاً.
   */
  onBackdropPress?: () => void;
}) {
  return (
    <KeyboardAvoidingView style={style} behavior="padding">
      {onBackdropPress ? <Pressable style={StyleSheet.absoluteFill} onPress={onBackdropPress} /> : null}
      {children}
    </KeyboardAvoidingView>
  );
}
