/**
 * عطبُ الطباعة بجملةٍ تقول ما يُفعل، لا برمزٍ إنجليزيٍّ يُصوَّر ويُرسل.
 *
 * وكانت هنا في شاشة الإعدادات وحدَها، بينما الشاشةُ التي يُصوّرها
 * صاحبُ المطعم فعلاً هي «قائمة الطباعة» -- فكان يقرأ فيها
 * PRINTER_CONNECTION_FAILED (connection_failed) ولا يعرف منها شيئاً.
 * فصارت في موضعٍ واحدٍ تقرؤه الشاشتان: نسختان تفترقان أسوأُ من
 * واحدةٍ ناقصة، لأنّ الناقصةَ تُرى.
 */
export function failureSentence(detail?: string): string {
  switch (detail) {
    case 'connection_refused':
      return 'الطابعة ردّت لكن رفضت هذا المنفذ — الرقم غلط. المعتاد 9100، والرقم الصحيح مكتوب في تقرير الشبكة اللي تطبعه الطابعة نفسها.';
    case 'permission_denied_local_network':
      return 'النظام مانع التطبيق من الشبكة المحلية — من إعدادات الجهاز: ركين ← فعّل «الشبكة المحلية».';
    case 'host_unreachable':
      return 'العنوان مو على شبكتك — تأكد إن الجهاز والطابعة على نفس الراوتر.';
    case 'connection_timeout':
      return 'ما رد أحد على هذا العنوان — تأكد إن الطابعة مشغّلة وموصولة، وإن ما فيه تطبيق ثاني ماسك الطابعة.';
    case 'invalid_port':
      return 'رقم المنفذ غير صالح.';
    case 'permission_denied':
      return 'ما انسمح للتطبيق يستخدم الطابعة — اضغط «اختبار الاتصال» مرة ثانية واختر «سماح».';
    case 'permission_request_failed':
      return 'الجهاز ما عرض طلب إذن الطابعة — افصل سلك الطابعة وركّبه، وجرّب مرة ثانية.';
    /* الأربعةُ التي كانت كلمةً واحدة (UsbPrinterTransport.kt).
       وكلٌّ منها يدٌ مختلفةٌ تمتدّ: سلكٌ، أو إذنٌ، أو تطبيقٌ ماسك،
       أو طابعةٌ واقفةٌ في نصّ ورقة. فجملةٌ عامّةٌ لا تُصلح أيّاً منها. */
    case 'usb_open_failed':
      return 'الطابعة موصولة بس ما انفتحت — افصل سلكها وركّبه، ولو ما نفع أقفل التطبيق وافتحه.';
    case 'usb_permission_lost':
      return 'الطابعة رجعت بعد انقطاع وسقط إذنها — اضغط «اختبار الاتصال» واختر «سماح».';
    case 'usb_claim_failed':
      return 'فيه شيء ثاني ماسك الطابعة — أقفل أي تطبيق طباعة ثاني، ولو ما نفع أقفل ركين وافتحه.';
    case 'usb_debt_unsettled':
      return 'الطابعة واقفة في نص فاتورة قبلها — افصل سلكها وركّبه عشان ترجع لأولها.';
    case 'usb_io_error':
      return 'انقطع الاتصال وهي ترسل — تأكد من السلك ومن كهرباء الطابعة.';
    /* وهذا كان يقع على الجملة العامّة «تأكد إنها على نفس الشبكة» --
       وهي نصيحةٌ لا معنى لها لطابعة USB، فيُرسل صاحبُ المطعم صورتَها
       ونحن أرسلناه إلى الراوتر. والانقطاعُ في نصِّ الإرسال سببُه
       الكابلُ أو كهرباءُ الطابعة، لا الشبكة. */
    case 'truncated_write':
      return 'انقطع الإرسال في نص الفاتورة — جرّب كيبل USB ثاني وأقصر، وخلّ الطابعة على كهربا مستقلة مو على الجهاز.';
    case 'device_not_found':
      return 'الطابعة مو موصولة الحين — تأكد من السلك، واضغط «البحث عن الأجهزة» واخترها من جديد.';
    default:
      return 'ما قدرنا نوصل للطابعة — تأكد إنها مشغّلة وعلى نفس الشبكة.';
  }
}


/**
 * فشلُ البحث عن الأجهزة، بجملةٍ تقول ما يُفعل.
 *
 * وكانت الشاشة تكتب «خطأ: permission_denied» -- رمزٌ إنجليزيٌّ أمام
 * كاشيرٍ عربيّ، ولا طريقَ منه إلى الحلّ. وأشهرُ سببَين لا يُحلّان من
 * داخل التطبيق أصلاً: إذنُ «الأجهزة القريبة» من إعدادات النظام،
 * والبلوتوثُ المقفل. فاسمُ العطب وحدَه يترك صاحبَ المطعم واقفاً.
 */
export function scanFailureSentence(detail?: string): string {
  switch (detail) {
    case 'permission_denied':
      return 'ما انسمح للتطبيق يشوف الأجهزة القريبة — اضغط «البحث عن الأجهزة» مرة ثانية واختر «سماح». ولو ما طلع لك الطلب: إعدادات الجهاز ← التطبيقات ← ركين ← الأذونات ← الأجهزة القريبة ← سماح.';
    case 'bluetooth_unavailable':
      return 'البلوتوث مقفل — شغّله من إعدادات الجهاز وجرّب مرة ثانية.';
    case 'usb_unavailable':
      return 'ما فيه منفذ USB على هذا الجهاز.';
    default:
      return 'ما قدرنا نبحث عن الأجهزة — جرّب مرة ثانية.';
  }
}

/** ولا أجهزة: الاقترانُ أوّلاً. والتطبيق لا يقرن بنفسه -- الاقترانُ
 *  حوارُ رمزٍ يملكه النظام وحده (BluetoothClassicPrinterTransport.kt). */
export function noDevicesSentence(transport: 'bluetooth' | 'usb'): string {
  return transport === 'bluetooth'
    ? 'ما لقينا أجهزة. تأكد إن الطابعة مشغّلة وقريبة، ولازم تكون مقترنة من إعدادات بلوتوث الجهاز أول — التطبيق ما يقدر يقرنها بنفسه.'
    : 'ما لقينا أجهزة. تأكد إن سلك الطابعة موصول وإنها مشغّلة.';
}