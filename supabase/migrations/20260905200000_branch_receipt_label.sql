-- ما يُطبع للفرع في ترويسة الفاتورة.
--
-- عمود مستقل عن branches.name عمداً: الاسم يظهر في اختيار الفرع وفي
-- التقارير وفي شاشة الفروع، وتغييره ليناسب ورقةً يغيّره في كل مكان.
-- وهذا يُكتب ليُقرأ على ورقة عرضها ثمانون مليمتراً -- "الفرع الأول" أو
-- "١" -- وقد لا يريده صاحب المطعم أصلاً.
--
-- والفراغ يعني لا تطبعه. هذا ما يجعل القاعدة صريحة بدل أن تكون استنتاجاً
-- من عدد الفروع: من أراد اسم فرعه على الورقة كتبه، ومن لم يُرِده تركه.
alter table branches add column if not exists receipt_label text;

comment on column branches.receipt_label is
  'اسم أو رقم الفرع كما يُطبع في ترويسة الفاتورة. فارغ = لا يُطبع.';
