-- فاتورةُ الاسترجاع: تُطبع أو لا تُطبع، بقرار صاحب المطعم.
--
-- الاسترجاعُ حركةٌ ماليةٌ تُخرج نقداً من الدرج، وورقةٌ تُثبتها ليست
-- زينة: يأخذها الزبون، وتبقى نسخةٌ في الدرج تُطابَق بها الوردية عند
-- الإقفال. ومطاعمُ كثيرة تُلزم بها، ومنها ما لا يريدها -- استرجاعٌ
-- بريالين لا يستحقّ ورقة.
--
-- والافتراضُ الطباعة: من لم يُسأل يُفترض أنه يريد الأثر، لا أن يفقده.

alter table businesses
  add column if not exists receipt_print_refund boolean not null default true;

comment on column businesses.receipt_print_refund is
  'تُطبع فاتورة استرجاع بعد كل عملية استرجاع. الافتراضي: نعم.';
