/**
 * الصورةُ إلى بايتاتِ ESC/POS -- شرائحُ `GS v 0`، لا شيءَ غيرُها.
 *
 * ── لماذا شرائح ──
 * أمرٌ واحدٌ لمئةِ كيلوبايتٍ يعني أنّ الطابعةَ تنتظر مئةَ كيلوبايتٍ
 * بالضبط: إن انقطع الإرسالُ في منتصفها بقيت تبتلع كلَّ ما يأتي بعده
 * كأنّه بقيّةُ الصورة -- فتخرج فاتورةٌ «محيوسة» ثمّ مترُ ورقٍ رموزاً.
 * وقع هذا عند مطعمٍ حقيقيٍّ على طابعة TA POS، ورآه المالكُ بعينه.
 * وبالشرائح يبقى الضررُ محصوراً في شريحةٍ بطول سنتيمترٍ ونصف.
 *
 * ── ولماذا لا يُدفع البياضُ بأمرِ تغذية ──
 * جُرّب في ١٫٧٩: نصفُ الفاتورة أسطرٌ بيضاءُ تماماً، فاستُبدلت بـ
 * `ESC J n` (اطبع وادفع n نقطة) -- ثلاثةُ بايتاتٍ بدل اثنين وسبعين
 * للسطر. وانكمشت الفاتورةُ من ٨٧ ك.ب إلى ٥٧، وقيل حينها إنّ «الورقةَ
 * هي هي نقطةً نقطة» لأنّ `GS v 0` يدفع الورقَ بمقدار ارتفاعه و
 * `ESC J n` يدفعه n نقطة.
 *
 * **وهذا كان افتراضاً لا قياساً.** مقدارُ ما يدفعه `ESC J n` هو
 * n × «وحدةِ الحركة الرأسيّة»، وهي قيمةٌ تختلف بين الطابعات ويضبطها
 * `GS P`، ومنها ما لا يُنفّذ الأمرَ أصلاً. فعلى طابعة EZPOS عند
 * «كباب طارق» سقط الدفعُ كلُّه: التصقت شرائحُ الحبر بعضُها ببعض،
 * وخرجت الفاتورةُ **مضغوطةً والكلامُ قريبٌ من بعضه جداً** -- وهو
 * بالضبط ما يحرّمه شرطُ المالك: لا يُغيَّر شكلُ الفاتورة.
 *
 * ولم يكشفه اختبارٌ ولا حارس، لأنّ كليهما كان يفكّ الناتجَ على نفس
 * الافتراض الذي بُني عليه: `ESC J n` يساوي n سطراً أبيض. اتّساقٌ مع
 * النفس، لا قياسٌ على ورق.
 *
 * فعاد البياضُ بايتاتِ صورة. وبياناتُ الصورة هي الشيءُ الوحيدُ الذي
 * لا تملك الطابعةُ فيه رأياً: سطرٌ أبيضُ يُطبع بياضاً على كلِّ طابعة،
 * بلا وحدةِ حركةٍ ولا أمرٍ قد لا يُفهم. والثمنُ بايتاتٌ أكثرُ على
 * الوصل -- ونحتمله: فاتورةٌ بطيئةٌ تُقرأ، والمضغوطةُ لا تُقرأ.
 *
 * ومن أراد إعادةَ المكسب فطريقُه ورقٌ حقيقيٌّ من طابعةِ مطعمٍ، لا
 * اختبارٌ يفكّ ما كتبَه هو.
 */

/**
 * ارتفاعُ الشريحة الواحدة بالأسطر.
 *
 * على ورق ٨٠مم (٧٢ بايتاً للسطر) = ٩٢١٦ بايتاً للشريحة -- أقلُّ من
 * قطعةِ الإرسال على USB (١٦ ك.ب)، فتمرّ كلُّ شريحةٍ في دفعةٍ واحدة.
 */
export const BAND_ROWS = 128;

interface Chunk {
  readonly y: number;
  readonly rows: number;
}

/**
 * يقسم الصفحةَ إلى شرائحَ متتاليةٍ لا تطول واحدةٌ منها عن الحدّ.
 *
 * ويُصدَّر للاختبار وللحارس: التقسيمُ هو الذي يجب أن يتطابق بين
 * العميلين، لا الناتجُ وحده.
 */
export function rasterChunks(_bitmap: Uint8Array, _bytesPerRow: number, height: number): Chunk[] {
  const out: Chunk[] = [];
  for (let y = 0; y < height; y += BAND_ROWS) {
    out.push({ y, rows: Math.min(BAND_ROWS, height - y) });
  }
  return out;
}

/**
 * الصورةُ بايتاتٍ جاهزةً: `GS v 0` لكلِّ شريحة، ولا أمرَ غيرُه.
 *
 * ولا رأسَ ولا ذيلَ هنا (التهيئةُ والقصّ عند المنادي): هذي الصورةُ
 * وحدَها، ليستعملها العميلان كما هي.
 */
export function bandRaster(bitmap: Uint8Array, bytesPerRow: number, height: number): Uint8Array {
  const chunks = rasterChunks(bitmap, bytesPerRow, height);
  let size = 0;
  for (const c of chunks) size += 8 + c.rows * bytesPerRow;
  const out = new Uint8Array(size);
  let at = 0;
  for (const c of chunks) {
    out[at] = 0x1d; out[at + 1] = 0x76; out[at + 2] = 0x30; out[at + 3] = 0x00;
    out[at + 4] = bytesPerRow & 0xff;
    out[at + 5] = (bytesPerRow >> 8) & 0xff;
    out[at + 6] = c.rows & 0xff;
    out[at + 7] = (c.rows >> 8) & 0xff;
    at += 8;
    out.set(bitmap.subarray(c.y * bytesPerRow, (c.y + c.rows) * bytesPerRow), at);
    at += c.rows * bytesPerRow;
  }
  return out;
}
